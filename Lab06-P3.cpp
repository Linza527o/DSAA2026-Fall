#include <iostream>
#include <vector>
#include <string>
using namespace std;
int main() {
    string s;
    cin >> s;
    vector<char> in(s.begin(), s.end());
    vector<vector<int>> a(in.size(), vector<int>(26, 0));
    for (int i = 0; i < in.size(); i++) {
        a[i][in[i] - 'a'] = i + 1;
    }
    int l = 0;
    for (int i = 0; i < 26; i++) {
        cout<<a[0][i]<<" ";
    }
    cout<<"\n";
    for (int i = 1;i<in.size();i++) {

        // for (int j = 1;j<=i;j++) {
        //
        // }
        for (int j = 0;j<26;j++) {
            if (a[i][j] == 0) {
                a[i][j] = a[l][j];
            }
            cout<< a[i][j]<<" ";
        }
        l = a[l][in[i]- 'a'];
        cout<<"\n";
    }
}

